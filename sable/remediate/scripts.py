"""RM-01 / RM-04: generate fix.sh and rollback.sh from completed results.

fix.sh records the original owner/mode of every file it touches (into a state file)
before changing it, then applies only chmod/chown fixes. rollback.sh reads that state
file and restores every path exactly, so re-running it leaves stat output identical.
sudo/service/capability/manual fixes are never scripted — they are listed as
commented manual recommendations (RM-04).
"""
import shlex

from sable.remediate.operations import is_applyable, paths_of

SHEBANG = '#!/usr/bin/env bash'
PREAMBLE = 'set -euo pipefail'
STATE_DEFAULT = 'sable-remediation-state.tsv'


def _fix_script(fixes):
    lines = [
        SHEBANG,
        PREAMBLE,
        '# Generated by SABLE from completed results. Review before running, and only',
        '# on a host you are authorised to change. Applies chmod/chown fixes only.',
        f'STATE="${{SABLE_STATE:-{STATE_DEFAULT}}}"',
        ': > "$STATE"',
        'record() { stat -c "%n\t%a\t%U\t%G" "$1" >> "$STATE"; }',
        '',
    ]
    manual = []
    applied = 0
    for fix in fixes:
        if is_applyable(fix):
            lines.append(f'# {fix["id"]} ({fix["type"]}): {fix["description"]}')
            for path in paths_of(fix):
                lines.append(f'record {shlex.quote(path)}')
            lines.append(fix['command'])
            lines.append('')
            applied += 1
        else:
            manual.append(f'# {fix["id"]} ({fix["type"]}, recommend-only): {fix["description"]}')
            manual.append(f'#   {fix["command"]}')
    if manual:
        lines.append('# Manual recommendations (NOT applied by this script - act by hand):')
        lines.extend(manual)
        lines.append('')
    return '\n'.join(lines).rstrip('\n') + '\n', applied


def _rollback_script():
    lines = [
        SHEBANG,
        PREAMBLE,
        f'STATE="${{SABLE_STATE:-{STATE_DEFAULT}}}"',
        '# Restore the recorded owner and mode for every path fix.sh changed.',
        'while IFS=$\'\\t\' read -r path mode owner group; do',
        '  chown "$owner:$group" "$path"',
        '  chmod "$mode" "$path"',
        'done < "$STATE"',
        '',
    ]
    return '\n'.join(lines)


def generate_scripts(results):
    """Return {'fix.sh': str, 'rollback.sh': str, 'applied': int} for the selected fixes."""
    fixes = results.get('fixes', [])
    fix_text, applied = _fix_script(fixes)
    return {'fix.sh': fix_text, 'rollback.sh': _rollback_script(), 'applied': applied}


def write_scripts(results, output_dir):
    """Write fix.sh and rollback.sh under output_dir; return the written paths."""
    from pathlib import Path
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    scripts = generate_scripts(results)
    written = {}
    for name in ('fix.sh', 'rollback.sh'):
        path = output / name
        path.write_text(scripts[name], encoding='utf-8')
        try:
            path.chmod(0o755)
        except OSError:
            pass
        written[name] = path
    return written
